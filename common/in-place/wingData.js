/** 扁平化成待写入的光翼列表（保留所属地图名，便于提示） */
export function flattenWings() {
    const out = []
    for (const row of WING_DATA) {
        const mapId = row[0]
        const mapName = row[1]
        for (let i = 2; i < row.length; i++) {
            out.push({ mapId, mapName, wingName: row[i] })
        }
    }
    return out
}